import { describe, it, expect, vi, beforeEach } from 'vitest';
import type { NextApiRequest, NextApiResponse } from 'next';

// The DeepL proxy used to keep its only auth check inside the per-item
// `Promise.all(text.map(...))` callback. That had two defects:
//   1. On an unauthenticated request it ran `res.status(401)` inside the map and
//      then still ran the success `res.status(200)` at the end — two responses
//      for one request (a 500 "headers already sent" in production).
//   2. A non-array `text` body threw inside `.map` and surfaced as an opaque
//      500 instead of a 400.
// The fix authenticates and validates `text` up front, before the loop.

const validateUserAndTokenMock = vi.fn();
// Resettable so a single test can pick a small quota to exercise the
// cumulative cap; defaults to effectively unlimited for the other cases.
let dailyQuota = 1_000_000_000;

vi.mock('@/utils/cors', () => ({
  corsAllMethods: {},
  runMiddleware: vi.fn().mockResolvedValue(undefined),
}));
vi.mock('@opennextjs/cloudflare', () => ({
  getCloudflareContext: () => ({ env: {} }),
}));
vi.mock('@/utils/access', () => ({
  validateUserAndToken: (...a: unknown[]) => validateUserAndTokenMock(...a),
  getSubscriptionPlan: () => 'free',
  getDailyTranslationPlanData: () => ({ quota: dailyQuota }),
}));
// `getCurrentUsageOrThrow` is the fail-closed usage read the quota check uses:
// it rejects (rather than returning 0) when the usage counter can't be read, so
// a Supabase outage cannot let translation proceed unmetered.
const usageMocks = vi.hoisted(() => ({
  getCurrentUsage: vi.fn().mockResolvedValue(0),
  getCurrentUsageOrThrow: vi.fn().mockResolvedValue(0),
  trackUsage: vi.fn().mockResolvedValue(0),
}));
vi.mock('@/utils/usage', () => ({
  UsageStatsManager: usageMocks,
}));
// The translators barrel (reached via ErrorCodes) transitively imports
// `@/utils/simplecc`, which loads a vendored WASM build that is generated by
// `pnpm setup-pdfjs`/`copy-simplecc` and absent in a bare checkout. Stub it so
// the route module loads without that build step.
vi.mock('@/utils/simplecc', () => ({
  initSimpleCC: vi.fn().mockResolvedValue(undefined),
  runSimpleCC: (s: string) => s,
}));

import handler from '@/pages/api/deepl/translate';

const makeReqRes = (body: Record<string, unknown>) => {
  const req = {
    method: 'POST',
    headers: { authorization: 'Bearer tok' },
    body,
  } as unknown as NextApiRequest;
  const res = {
    status: vi.fn().mockReturnThis(),
    json: vi.fn().mockReturnThis(),
  } as unknown as NextApiResponse;
  return { req, res };
};

beforeEach(() => {
  validateUserAndTokenMock.mockReset();
  dailyQuota = 1_000_000_000;
  usageMocks.getCurrentUsage.mockReset().mockResolvedValue(0);
  usageMocks.getCurrentUsageOrThrow.mockReset().mockResolvedValue(0);
  usageMocks.trackUsage.mockReset().mockResolvedValue(0);
});

describe('POST /api/deepl/translate — auth + input validation', () => {
  it('returns a single 401 for an unauthenticated request (no double response)', async () => {
    validateUserAndTokenMock.mockResolvedValue({ user: null, token: null });
    const { req, res } = makeReqRes({ text: ['hello'] });

    await handler(req, res);

    // The bug sent two responses (401 then 200); the fix sends exactly one.
    expect(res.status).toHaveBeenCalledTimes(1);
    expect(res.status).toHaveBeenCalledWith(401);
  });

  it('returns 400 for a non-array text body instead of a 500', async () => {
    validateUserAndTokenMock.mockResolvedValue({ user: { id: 'u1' }, token: 'tok' });
    const { req, res } = makeReqRes({ text: 123 });

    await handler(req, res);

    expect(res.status).toHaveBeenCalledTimes(1);
    expect(res.status).toHaveBeenCalledWith(400);
  });

  it('returns 400 when text contains a non-string element', async () => {
    validateUserAndTokenMock.mockResolvedValue({ user: { id: 'u1' }, token: 'tok' });
    const { req, res } = makeReqRes({ text: ['ok', 42] });

    await handler(req, res);

    expect(res.status).toHaveBeenCalledWith(400);
  });
});

describe('POST /api/deepl/translate — cumulative quota + size caps', () => {
  it('rejects an oversized batch (500 items × 9000 chars) before translating any item', async () => {
    validateUserAndTokenMock.mockResolvedValue({ user: { id: 'u1' }, token: 'tok' });
    const text = Array.from({ length: 500 }, () => 'a'.repeat(9000));
    const { req, res } = makeReqRes({ text });

    await handler(req, res);

    // The per-item check used to let each 9000-char item pass against the same
    // zero-usage snapshot, translating all 4.5M chars. The size cap now rejects
    // the batch outright, and never with a success status.
    expect(res.status).toHaveBeenCalledWith(413);
    expect(res.status).not.toHaveBeenCalledWith(200);
  });

  it('rejects when the summed character count exceeds the daily quota even if each item fits', async () => {
    // Free daily quota is 10 KiB. Two 8000-char items each pass an individual
    // check (8000 < 10240) but together (16000) blow the quota — the old
    // per-item check missed this; the cumulative check catches it as a 429.
    dailyQuota = 10 * 1024;
    validateUserAndTokenMock.mockResolvedValue({ user: { id: 'u1' }, token: 'tok' });
    const { req, res } = makeReqRes({ text: ['a'.repeat(8000), 'b'.repeat(8000)] });

    await handler(req, res);

    expect(res.status).toHaveBeenCalledWith(429);
    expect(res.status).not.toHaveBeenCalledWith(200);
  });

  it('fails closed and makes no DeepL request when the daily usage counter cannot be read', async () => {
    // The usage read used to return 0 on a Supabase error, so a read failure
    // made every sub-quota request pass and translate unmetered. The strict
    // read now rejects, so the handler must reject BEFORE any upstream DeepL
    // call. A fetch spy proves the translation never left the Worker (a plain
    // "not 200" check would also pass if fetch were called and merely failed).
    const fetchSpy = vi.fn();
    vi.stubGlobal('fetch', fetchSpy);
    try {
      validateUserAndTokenMock.mockResolvedValue({ user: { id: 'u1' }, token: 'tok' });
      usageMocks.getCurrentUsageOrThrow.mockRejectedValue(new Error('usage read failed'));
      const { req, res } = makeReqRes({ text: ['hello world'] });

      await handler(req, res);

      expect(fetchSpy).not.toHaveBeenCalled();
      expect(res.status).not.toHaveBeenCalledWith(200);
      expect(res.status).toHaveBeenCalledWith(500);
    } finally {
      vi.unstubAllGlobals();
    }
  });
});
